/*!
The four conformance tables, over the shared `text_bid_dpd` corpus.

The vectors are read straight out of `resources/text_bid_dpd` — the
`decimal128-resources` submodule — and were generated by the `decimal128-c`
engine through its public API. That engine reaches its answers by different
algorithms than this codec does, so agreement is a cross-check rather than a
tautology.

```text
  T1 DECODE  bid -> text and dpd -> text          (100, noncanonical)
  T2 ENCODE  text -> bid and text -> dpd          (100)
  T3 PARSE   input text -> bits, both formats     (parse, 1,061 rows)
  T4 ERROR   malformed input text -> rejection    (error, 173 rows)
```

Plus the cross-format assertion: for every row both encodings must render to the
same text. That is the strongest property the corpus encodes.

The fifth table, `canonical`, is 84,783 rows of mostly common-path volume and
runs as `canonical_table_decodes_and_re_encodes` at the bottom of this file.

This is an integration test, so it links the crate from outside and can reach
only the public surface — the same surface a consumer has.
*/

use decimal128_text_codec::{
    MAX_LEN, QNAN, bid128_parse, bid128_to_ascii, dpd128_parse, dpd128_to_ascii,
};

// ---------------------------------------------------------------------------
// The tables
// ---------------------------------------------------------------------------

/// T1: every row's two encodings must render to the expected text.
#[test]
fn hundred_decodes() {
    let rows = load_corpus(HUNDRED);
    assert_row_count(&rows, 100, HUNDRED);
    run_decode_table(&rows, "100");
}

/// T2: and the text must encode back to the same bits.
#[test]
fn hundred_re_encodes() {
    let rows = load_corpus(HUNDRED);
    assert_row_count(&rows, 100, HUNDRED);
    run_encode_table(&rows, "100");
}

/// One-way rows: both encodings decode to the text, but at least one is a bit
/// pattern the canonical encoder would never emit, so re-encoding is
/// deliberately not asserted.
#[test]
fn non_canonical_encodings_render_correctly() {
    let rows = load_corpus(NON_CANONICAL);
    assert_row_count(&rows, 1267, NON_CANONICAL);
    run_decode_table(&rows, "noncanonical");
}

/// T3: the only table that reaches the rounding surface at all.
#[test]
fn parse_vectors_produce_both_encodings() {
    let rows = load_corpus(PARSE);
    assert_row_count(&rows, 1061, PARSE);
    for row in &rows {
        let mut bits = 0u128;
        if let Some(e) = bid128_parse(&mut bits, &row.text) {
            panic!(
                "parse line {}: bid rejected <{}>: {e}",
                row.line_number, row.text
            );
        }
        assert!(
            bits == row.bid,
            "parse line {}: bid <{}> gave {}, expected {}",
            row.line_number,
            row.text,
            hex32(bits),
            row.bid_hex()
        );
        if let Some(e) = dpd128_parse(&mut bits, &row.text) {
            panic!(
                "parse line {}: dpd rejected <{}>: {e}",
                row.line_number, row.text
            );
        }
        assert!(
            bits == row.dpd,
            "parse line {}: dpd <{}> gave {}, expected {}",
            row.line_number,
            row.text,
            hex32(bits),
            row.dpd_hex()
        );
    }
}

/*
 * A value the out-parameter is seeded with before a parse that must fail. It is
 * neither `QNAN` nor any encoding the corpus expects, so the post-condition
 * check below is testing that the parser wrote, not that it happened to leave
 * the right bits in place.
 */
const SEED: u128 = 0xDEAD_BEEF_DEAD_BEEF_DEAD_BEEF_DEAD_BEEF;

/*
 * T4: malformed input. Both formats must reject, must agree on the reason, and
 * must leave the canonical positive quiet NaN behind in the out-parameter.
 *
 * That third assertion is why the corpus carries that pattern in the bits
 * columns of this table, and it is asserted here exactly as the sibling ports
 * assert it — against `row.bid`, the engine-authored pattern, on all 173 rows.
 * The out-parameter is seeded with a value that is neither the expected result
 * nor `QNAN`, so a parser that returned the message without writing would be
 * caught rather than passing on a coincidence.
 *
 * The two formats' failures are compared with `==` on the messages themselves,
 * which is the siblings' `strcmp(bErr, dErr)` and not a proxy for it: a failure
 * IS the message here, as it is there.
 */
#[test]
fn error_vectors_are_rejected_by_both_formats() {
    let rows = load_corpus(ERROR);
    assert_row_count(&rows, 173, ERROR);
    for row in &rows {
        let mut bid_bits = SEED;
        let mut dpd_bits = SEED;
        let bid = bid128_parse(&mut bid_bits, &row.text);
        let dpd = dpd128_parse(&mut dpd_bits, &row.text);
        assert!(
            bid.is_some(),
            "error line {}: bid ACCEPTED <{}>, corpus says {}",
            row.line_number,
            row.text,
            row.status
        );
        assert!(
            dpd.is_some(),
            "error line {}: dpd ACCEPTED <{}>, corpus says {}",
            row.line_number,
            row.text,
            row.status
        );
        if let Some(b) = bid {
            assert!(
                b == row.status,
                "error line {}: <{}> returned <{b}>, corpus says {}",
                row.line_number,
                row.text,
                row.status
            );
        }
        if let (Some(b), Some(d)) = (bid, dpd) {
            assert!(
                b == d,
                "error line {}: the formats disagree on <{}>: <{b}> vs <{d}>",
                row.line_number,
                row.text
            );
        }
        assert!(
            bid_bits == row.bid,
            "error line {}: bid rejected <{}> but left {}, corpus says {}",
            row.line_number,
            row.text,
            hex32(bid_bits),
            row.bid_hex()
        );
        assert!(
            dpd_bits == row.dpd,
            "error line {}: dpd rejected <{}> but left {}, corpus says {}",
            row.line_number,
            row.text,
            hex32(dpd_bits),
            row.dpd_hex()
        );
        assert!(
            QNAN == row.bid,
            "error line {}: the corpus failure pattern is {}, but QNAN is {}",
            row.line_number,
            row.bid_hex(),
            hex32(QNAN)
        );
    }
}

/*
 * The reader itself. `parse` and `error` quote their text column, and the four
 * rows below are exactly the ones a naive comma split corrupts while still
 * passing — a mangled malformed input fails to parse either way.
 */
#[test]
fn quoted_column_round_trips() {
    let rows = load_corpus(ERROR);
    let texts: Vec<&str> = rows.iter().map(|r| r.text.as_str()).collect();
    assert!(
        texts.iter().any(|t| t.is_empty()),
        "the empty-string row was lost"
    );
    assert!(
        texts.iter().any(|t| t.starts_with(' ')),
        "a leading-space row was lost"
    );
    assert!(
        texts.iter().any(|t| t.ends_with(' ')),
        "a trailing-space row was lost"
    );
    assert!(
        texts.iter().any(|t| t.contains(',')),
        "an embedded-comma row was lost"
    );
}

/*
 * The full canonical table, read from the same submodule as the rest. It is a
 * test of its own only because it is two orders of magnitude bigger than the
 * other four put together, not because it is optional.
 */
#[test]
fn canonical_table_decodes_and_re_encodes() {
    let rows = load_corpus(CANONICAL);
    assert_row_count(&rows, 84783, CANONICAL);
    run_decode_table(&rows, "canonical");
    run_encode_table(&rows, "canonical");
}

// ---------------------------------------------------------------------------
// The two table runners
// ---------------------------------------------------------------------------

/// Every row: both encodings must render to the expected text, and therefore to
/// each other.
fn run_decode_table(rows: &[CorpusRow], label: &str) {
    let mut buf = [0u8; MAX_LEN];
    for row in rows {
        let bid_text = bid128_to_ascii(&mut buf, row.bid);
        assert!(
            bid_text == row.text,
            "{label} line {}: bid #{} rendered <{bid_text}>, expected <{}>",
            row.line_number,
            row.bid_hex(),
            row.text
        );
        let dpd_text = dpd128_to_ascii(&mut buf, row.dpd);
        assert!(
            dpd_text == row.text,
            "{label} line {}: dpd #{} rendered <{dpd_text}>, expected <{}>",
            row.line_number,
            row.dpd_hex(),
            row.text
        );
    }
}

/// Round-trippable rows: the text must encode back to the same bits.
fn run_encode_table(rows: &[CorpusRow], label: &str) {
    for row in rows {
        let mut bits = 0u128;
        if let Some(e) = bid128_parse(&mut bits, &row.text) {
            panic!(
                "{label} line {}: bid rejected <{}>: {e}",
                row.line_number, row.text
            );
        }
        assert!(
            bits == row.bid,
            "{label} line {}: bid <{}> gave {}, expected {}",
            row.line_number,
            row.text,
            hex32(bits),
            row.bid_hex()
        );
        if let Some(e) = dpd128_parse(&mut bits, &row.text) {
            panic!(
                "{label} line {}: dpd rejected <{}>: {e}",
                row.line_number, row.text
            );
        }
        assert!(
            bits == row.dpd,
            "{label} line {}: dpd <{}> gave {}, expected {}",
            row.line_number,
            row.text,
            hex32(bits),
            row.dpd_hex()
        );
    }
}

// ---------------------------------------------------------------------------
// One row of a text_bid_dpd table: the text, the two encodings, and the status
// column the input-driven tables carry.
// ---------------------------------------------------------------------------

struct CorpusRow {
    text: String,
    bid: u128,
    dpd: u128,
    status: String,
    line_number: usize,
}

impl CorpusRow {
    /// The encoding as the corpus spells it: 32 uppercase hex digits.
    fn bid_hex(&self) -> String {
        hex32(self.bid)
    }
    fn dpd_hex(&self) -> String {
        hex32(self.dpd)
    }
}

fn hex32(bits: u128) -> String {
    format!("{bits:032X}")
}

/// Parse 32 hex digits, with or without a leading `0x`.
fn parse_hex32(s: &str) -> Option<u128> {
    let body = s
        .strip_prefix("0x")
        .or_else(|| s.strip_prefix("0X"))
        .unwrap_or(s);
    if body.len() != 32 {
        return None;
    }
    u128::from_str_radix(body, 16).ok()
}

// ---------------------------------------------------------------------------
// The shared conformance corpus, read from resources/text_bid_dpd — the
// decimal128-resources submodule, mounted at the repo root the way every
// decimal128 port mounts it. Nothing is copied into this repo.
//
// The row counts are asserted by the tests, and that is not ceremony: the text
// column of `parse` and `error` is double-quoted with backslash escapes, because
// those tables must carry the empty string, a leading and a trailing space, an
// embedded comma, an embedded quote and an embedded backslash. The other three
// leave it bare. A naive comma split silently corrupts four rows and still
// passes, since a mangled malformed input fails to parse either way. The row
// count is what catches it.
//
// The directory comes from CARGO_MANIFEST_DIR, which cargo bakes in at compile
// time — the analogue of the C port's compiled-in VECTOR_DIR, Swift's #filePath
// and C#'s [CallerFilePath]. An absolute DECIMAL128_RESOURCES overrides it.
// ---------------------------------------------------------------------------

const HUNDRED: &str = "text_bid128_dpd128_100";
const NON_CANONICAL: &str = "text_bid128_dpd128_noncanonical";
const PARSE: &str = "text_bid128_dpd128_parse";
const ERROR: &str = "text_bid128_dpd128_error";
const CANONICAL: &str = "text_bid128_dpd128_canonical";

/// Where the loader looked, for a failure message that names the fix.
const RESOURCES_HINT: &str = "the decimal128-resources submodule is not checked out: \
                              run `git submodule update --init --recursive`";

fn corpus_directory() -> std::path::PathBuf {
    match std::env::var("DECIMAL128_RESOURCES") {
        Ok(env) if !env.is_empty() => std::path::PathBuf::from(env).join("text_bid_dpd"),
        _ => std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("resources")
            .join("text_bid_dpd"),
    }
}

/// One table, read off the filesystem.
fn load_corpus(name: &str) -> Vec<CorpusRow> {
    let path = corpus_directory().join(format!("{name}.csv.txt"));
    let contents = match std::fs::read_to_string(&path) {
        Ok(c) => c,
        Err(e) => panic!(
            "{} could not be read ({e}) -- {RESOURCES_HINT}",
            path.display()
        ),
    };
    parse_table(&contents, name)
}

fn assert_row_count(rows: &[CorpusRow], want: usize, name: &str) {
    assert!(
        rows.len() == want,
        "{name}.csv.txt has {} rows, expected {want}",
        rows.len()
    );
}

fn parse_table(contents: &str, name: &str) -> Vec<CorpusRow> {
    let mut rows = Vec::new();
    for (index, raw_line) in contents.split('\n').enumerate() {
        let line_number = index + 1;
        let line = skip_space(raw_line.trim_end_matches('\r'));
        if line.is_empty() || line.starts_with('#') {
            continue;
        }

        let (text, rest) = if line.starts_with('"') {
            read_quoted(line)
        } else {
            let (value, rest) = read_field(line);
            (value.to_string(), rest)
        };
        let (bid_field, rest) = read_next_field(rest);
        let (dpd_field, rest) = read_next_field(rest);
        let (status, _) = read_next_field(rest);

        let (Some(bid), Some(dpd)) = (parse_hex32(bid_field), parse_hex32(dpd_field)) else {
            panic!(
                "{name}.csv.txt line {line_number}: malformed hex columns <{bid_field}> <{dpd_field}>"
            );
        };
        rows.push(CorpusRow {
            text,
            bid,
            dpd,
            status: status.to_string(),
            line_number,
        });
    }
    rows
}

// -- the reader, matching the C, Swift, Kotlin, Java, C# and Go ports ---------

fn skip_space(s: &str) -> &str {
    s.trim_start_matches([' ', '\t'])
}

/// One comma-delimited field, stopping at `,` or `#` or end of line, with
/// surrounding whitespace trimmed. Returns the field and the unconsumed rest.
fn read_field(s: &str) -> (&str, &str) {
    let start = skip_space(s);
    let end = start.find([',', '#']).unwrap_or(start.len());
    (start[..end].trim_end_matches([' ', '\t']), &start[end..])
}

/// Step over a field separator, then read the next field. Yields the empty
/// string when the row has no further column.
fn read_next_field(s: &str) -> (&str, &str) {
    let rest = skip_space(s);
    match rest.strip_prefix(',') {
        Some(after) => read_field(after),
        None => ("", rest),
    }
}

/// The quoted text column, honouring backslash escapes.
fn read_quoted(s: &str) -> (String, &str) {
    let bytes = s.as_bytes();
    let mut out = String::new();
    let mut i = 1; // past the opening quote
    while i < bytes.len() && bytes[i] != b'"' {
        let mut c = bytes[i];
        i += 1;
        if c == b'\\' && i < bytes.len() {
            c = bytes[i];
            i += 1;
        }
        out.push(c as char);
    }
    if i < bytes.len() && bytes[i] == b'"' {
        i += 1;
    }
    (out, &s[i..])
}
